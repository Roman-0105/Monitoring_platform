-- Migration: Границы водных объектов (озёра/реки) для карты химии
--
-- Позволяет задать полигон-границу для водопункта (обычно — озеро
-- или река на карте), который карта химии (ui-wpmap.js) использует,
-- чтобы НЕ закрашивать эту область интерполяцией по соседним пробам
-- подземных вод (они гидравлически не связаны с открытой водой).
--
-- Формат: JSON-массив пар [lat, lng], минимум 3 точки, без замыкания
-- (последняя точка не дублирует первую — контур замыкается на клиенте).
--
-- ПОРЯДОК ВЫПОЛНЕНИЯ: выполните весь скрипт в Supabase SQL Editor.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE wp_registry
  ADD COLUMN IF NOT EXISTS boundary jsonb;

COMMENT ON COLUMN wp_registry.boundary IS
  'Полигон-граница водного объекта (озеро/река) для карты химии: JSON-массив [[lat,lng], ...], минимум 3 точки';
