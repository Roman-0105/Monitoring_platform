-- Migration: Квартал пробы для протоколов химического анализа
--
-- Результаты анализа поступают ежеквартально — добавляем поле "квартал"
-- к протоколу, чтобы фильтровать список протоколов и карту химии по
-- году+кварталу. Квартал вычисляется автоматически из даты отбора проб
-- (sampled_at) при сохранении протокола, но пользователь может задать
-- его вручную (например, если проба формально относится к другому
-- отчётному периоду, чем календарный месяц отбора).
--
-- ПОРЯДОК ВЫПОЛНЕНИЯ: выполните весь скрипт в Supabase SQL Editor.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE chem_protocols
  ADD COLUMN IF NOT EXISTS quarter smallint CHECK (quarter BETWEEN 1 AND 4);

COMMENT ON COLUMN chem_protocols.quarter IS
  'Квартал пробы (1-4) — автоматически из sampled_at при сохранении, можно задать вручную';

-- Автоматически проставляем квартал уже существующим протоколам —
-- без этого шага старые пробы не попадали бы ни в один квартальный фильтр.
UPDATE chem_protocols
SET quarter = CEIL(EXTRACT(MONTH FROM sampled_at)::numeric / 3)
WHERE quarter IS NULL AND sampled_at IS NOT NULL;
